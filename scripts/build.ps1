# Builds aec-mic.dll and the release zip without CMake.
#
#   ./scripts/build.ps1 [-ObsDll <path to obs.dll>] [-Version 0.1.0] [-Test]
#
# - Fetches only libobs headers from obs-studio at tag $ObsTag (sparse clone into deps/).
# - Generates an import library (obs.lib) from obs.dll's exports (OBS does not ship obs.lib).
# - Compiles with MSVC (found via vswhere) and packages build/obs-aec-mic-<version>-windows-x64.zip.
# Building against libobs 32.0.4 is deliberate: OBS refuses plugins built for a NEWER libobs, not older,
# so this binary loads on OBS 32.x and later.
param(
	[string]$ObsDll = "$env:ProgramFiles\obs-studio\bin\64bit\obs.dll",
	[string]$ObsTag = '32.0.4',
	[string]$Version = '0.1.0',
	[switch]$Test
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$build = Join-Path $root 'build'
$deps = Join-Path $root 'deps'
New-Item -ItemType Directory -Force $build, $deps | Out-Null

function Invoke-Checked([string]$exe, [string[]]$argList) {
	& $exe @argList
	if ($LASTEXITCODE -ne 0) { throw "$exe failed with exit code $LASTEXITCODE" }
}

# 1. libobs headers
$obsSrc = Join-Path $deps "obs-studio-$ObsTag"
if (-not (Test-Path (Join-Path $obsSrc 'libobs\obs-module.h'))) {
	if (Test-Path $obsSrc) { Remove-Item -Recurse -Force $obsSrc }
	Invoke-Checked git @('clone', '-q', '--depth', '1', '--branch', $ObsTag, '--filter=blob:none', '--sparse',
		'https://github.com/obsproject/obs-studio.git', $obsSrc)
	Invoke-Checked git @('-C', $obsSrc, 'sparse-checkout', 'set', 'libobs')
}
$inc = Join-Path $build 'include'
New-Item -ItemType Directory -Force $inc | Out-Null
# obsconfig.h is normally generated by OBS's CMake; plugins only need these definitions.
@(
	'#pragma once',
	'#define OBS_DATA_PATH "../../data"',
	'#define OBS_PLUGIN_PATH "../../obs-plugins/64bit"',
	'#define OBS_PLUGIN_DESTINATION "obs-plugins/64bit"',
	'#define OBS_RELEASE_CANDIDATE 0',
	'#define OBS_BETA 0'
) | Set-Content -Encoding ascii (Join-Path $inc 'obsconfig.h')
# Version as a header (avoids quoting a string macro through PowerShell -> cl).
"#pragma once`r`n#define AEC_MIC_VERSION `"$Version`"" | Set-Content -Encoding ascii (Join-Path $inc 'aec-mic-version.h')

# 2. MSVC environment
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
if (-not (Test-Path $vswhere)) { throw 'vswhere.exe not found: install Visual Studio Build Tools with the C++ workload' }
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'MSVC x64 tools not found (C++ build tools workload)' }
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'
cmd /c "`"$vcvars`" >nul && set" | ForEach-Object {
	if ($_ -match '^([^=]+)=(.*)$') { Set-Item -Path "env:$($Matches[1])" -Value $Matches[2] }
}

# 3. obs.lib from obs.dll exports
if (-not (Test-Path $ObsDll)) { throw "obs.dll not found at $ObsDll (pass -ObsDll)" }
$exports = & dumpbin /nologo /exports $ObsDll
$names = $exports | ForEach-Object {
	if ($_ -match '^\s+\d+\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]{8}\s+(\S+)') { $Matches[1] }
}
if (-not $names) { throw 'no exports found in obs.dll' }
$def = Join-Path $build 'obs.def'
@('LIBRARY obs', 'EXPORTS') + $names | Set-Content -Encoding ascii $def
Invoke-Checked lib @('/nologo', "/def:$def", '/machine:x64', "/out:$(Join-Path $build 'obs.lib')")

# 4. compile
$libobs = Join-Path $obsSrc 'libobs'
$common = @('/nologo', '/std:c++17', '/O2', '/EHsc', '/W3', '/utf-8', '/MD', '/DUNICODE', '/D_UNICODE',
	'/D_CRT_SECURE_NO_WARNINGS', "/I$inc", "/I$libobs")
Invoke-Checked cl ($common + @('/LD', (Join-Path $root 'src\aec-mic.cpp'),
	"/Fo$build\", "/Fe:$(Join-Path $build 'aec-mic.dll')", '/link', (Join-Path $build 'obs.lib'), 'ole32.lib', 'user32.lib'))
if ($Test) {
	Invoke-Checked cl ($common + @((Join-Path $root 'tests\test-plugin.cpp'), "/Fo$build\",
		"/Fe:$(Join-Path $build 'test-plugin.exe')", '/link', (Join-Path $build 'obs.lib'), 'winmm.lib'))
}

# 5. package: zip root has aec-mic\ (drop-in for C:\ProgramData\obs-studio\plugins) + install scripts
$pkg = Join-Path $build 'package'
if (Test-Path $pkg) { Remove-Item -Recurse -Force $pkg }
$mod = Join-Path $pkg 'aec-mic'
New-Item -ItemType Directory -Force (Join-Path $mod 'bin\64bit'), (Join-Path $mod 'data') | Out-Null
Copy-Item (Join-Path $build 'aec-mic.dll') (Join-Path $mod 'bin\64bit\')
Copy-Item -Recurse (Join-Path $root 'data\locale') (Join-Path $mod 'data\')
$manifest = Get-Content -Raw (Join-Path $root 'data\manifest.json') | ConvertFrom-Json
$manifest.version = $Version
# UTF-8 without BOM: Windows PowerShell's -Encoding utf8 writes a BOM, which JSON parsers may reject.
[IO.File]::WriteAllText((Join-Path $mod 'data\manifest.json'), ($manifest | ConvertTo-Json -Depth 5),
	(New-Object Text.UTF8Encoding $false))
Copy-Item (Join-Path $root 'scripts\install.bat'), (Join-Path $root 'scripts\uninstall.bat'), (Join-Path $root 'LICENSE') $pkg
$zip = Join-Path $build "obs-aec-mic-$Version-windows-x64.zip"
if (Test-Path $zip) { Remove-Item $zip }
Compress-Archive -Path (Join-Path $pkg '*') -DestinationPath $zip
"OK: $zip"
